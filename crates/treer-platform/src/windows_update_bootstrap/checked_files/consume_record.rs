//! Inert consume-intent data only: no writer, lock proof or consumed token.
const MAGIC: &[u8; 8] = b"TRCONS01";
const LENGTH: usize = 177;

#[derive(Clone, Debug, PartialEq, Eq)]
pub(super) struct Record {
    pub(super) lifetime: [u8; 32],
    pub(super) attempt: [u8; 32],
    pub(super) head_volume: u64,
    pub(super) head_file: [u8; 16],
    pub(super) head_hash: [u8; 32],
    pub(super) evidence_hash: [u8; 32],
    pub(super) component: u8,
    pub(super) role: u8,
    pub(super) operation: u8,
    pub(super) revision: u64,
    pub(super) status: u32,
}

fn identifier<const N: usize>(value: &[u8; N]) -> bool {
    *value != [0; N] && *value != [u8::MAX; N]
}

impl Record {
    fn valid(&self) -> bool {
        identifier(&self.lifetime)
            && identifier(&self.attempt)
            && !matches!(self.head_volume, 0 | u64::MAX)
            && identifier(&self.head_file)
            && matches!(self.component, 1 | 2)
            && matches!((self.role, self.operation), (1, 1) | (2, 2))
            && self.revision != 0
            && self.status != 0
    }

    pub(super) fn encode(&self) -> Option<Vec<u8>> {
        if !self.valid() {
            return None;
        }
        let mut bytes = Vec::with_capacity(LENGTH);
        bytes.extend(MAGIC);
        bytes.extend((LENGTH as u16).to_le_bytes());
        bytes.extend(self.lifetime);
        bytes.extend(self.attempt);
        bytes.extend(self.head_volume.to_le_bytes());
        bytes.extend(self.head_file);
        bytes.extend(self.head_hash);
        bytes.extend(self.evidence_hash);
        bytes.extend([self.component, self.role, self.operation]);
        bytes.extend(self.revision.to_le_bytes());
        bytes.extend(self.status.to_le_bytes());
        Some(bytes)
    }
}

fn take<const N: usize>(input: &mut &[u8]) -> Option<[u8; N]> {
    let value = input.get(..N)?.try_into().ok()?;
    *input = &input[N..];
    Some(value)
}

fn parse(mut input: &[u8]) -> Option<Record> {
    if input.len() != LENGTH
        || take::<8>(&mut input)? != *MAGIC
        || usize::from(u16::from_le_bytes(take(&mut input)?)) != LENGTH
    {
        return None;
    }
    let record = Record {
        lifetime: take(&mut input)?,
        attempt: take(&mut input)?,
        head_volume: u64::from_le_bytes(take(&mut input)?),
        head_file: take(&mut input)?,
        head_hash: take(&mut input)?,
        evidence_hash: take(&mut input)?,
        component: take::<1>(&mut input)?[0],
        role: take::<1>(&mut input)?[0],
        operation: take::<1>(&mut input)?[0],
        revision: u64::from_le_bytes(take(&mut input)?),
        status: u32::from_le_bytes(take(&mut input)?),
    };
    (input.is_empty() && record.valid()).then_some(record)
}

// Exact data comparison only. An independently trusted expectation, actual
// outcome and live custody are required elsewhere before any continuation.
pub(super) fn matches_expected(bytes: &[u8], expected: &Record) -> bool {
    parse(bytes).as_ref() == Some(expected)
}

pub(super) fn valid_bytes(bytes: &[u8]) -> bool {
    parse(bytes).is_some()
}

pub(super) fn fixture_bytes() -> Vec<u8> {
    fixture().encode().unwrap()
}

fn fixture() -> Record {
    Record {
        lifetime: [0x11; 32], // Synthetic, never supervisor ownership.
        attempt: [0x22; 32],
        head_volume: 0x0102030405060708,
        head_file: [0x33; 16],
        head_hash: [0x44; 32],
        evidence_hash: [0x55; 32],
        component: 2,
        role: 1,
        operation: 1,
        revision: 0x1112131415161718,
        status: 183,
    }
}

#[test]
fn native_consume_codec_literal_golden_and_every_byte() {
    // Independent literal wire bytes, not generated by this encoder.
    let hex = concat!(
        "5452434f4e533031b100",
        "1111111111111111111111111111111111111111111111111111111111111111",
        "2222222222222222222222222222222222222222222222222222222222222222",
        "0807060504030201",
        "33333333333333333333333333333333",
        "4444444444444444444444444444444444444444444444444444444444444444",
        "5555555555555555555555555555555555555555555555555555555555555555",
        "0201011817161514131211b7000000",
    );
    let golden: Vec<u8> = hex
        .as_bytes()
        .chunks_exact(2)
        .map(|pair| u8::from_str_radix(std::str::from_utf8(pair).unwrap(), 16).unwrap())
        .collect();
    let record = fixture();
    assert_eq!(golden.len(), LENGTH);
    assert_eq!(record.encode().unwrap(), golden);
    assert_eq!(parse(&golden), Some(record.clone()));
    for offset in 0..LENGTH {
        let mut changed = golden.clone();
        changed[offset] ^= 1;
        assert!(!matches_expected(&changed, &record), "offset {offset}");
    }
    // Copying bytes into another installation/lifetime is not an exact match.
    let mut foreign = record.clone();
    foreign.lifetime[31] ^= 1;
    assert!(!matches_expected(&golden, &foreign));
    foreign = record.clone();
    foreign.attempt[31] ^= 1;
    assert!(!matches_expected(&golden, &foreign));
}

#[test]
fn native_consume_codec_refuses_framing_and_cross_domains() {
    let bytes = fixture().encode().unwrap();
    for length in 0..LENGTH {
        assert!(parse(&bytes[..length]).is_none());
    }
    for tail in [vec![0], vec![0; 4], bytes.clone()] {
        let mut extra = bytes.clone();
        extra.extend(tail);
        assert!(parse(&extra).is_none());
    }
    for length in [0u16, 145, 176, 178, u16::MAX] {
        let mut changed = bytes.clone();
        changed[8..10].copy_from_slice(&length.to_le_bytes());
        assert!(parse(&changed).is_none());
    }
    for magic in [
        b"TRHEAD01",
        b"TRCTX001",
        b"PREDE001",
        b"TRCONS00",
        b"TRCONS02",
    ] {
        let mut changed = bytes.clone();
        changed[..8].copy_from_slice(magic);
        assert!(parse(&changed).is_none());
    }
    assert!(parse(&[1, 183, 0, 0, 0]).is_none());
}

#[test]
fn native_consume_codec_refuses_invalid_fields_and_accepts_bounds() {
    let bytes = fixture().encode().unwrap();
    for (start, length) in [(10, 32), (42, 32), (74, 8), (82, 16)] {
        for fill in [0, 255] {
            let mut changed = bytes.clone();
            changed[start..start + length].fill(fill);
            assert!(parse(&changed).is_none());
        }
    }
    for (offset, values) in [
        (162, vec![0, 3, 255]),
        (163, vec![0, 2, 3, 255]),
        (164, vec![0, 2, 3, 255]),
    ] {
        for value in values {
            let mut changed = bytes.clone();
            changed[offset] = value;
            assert!(parse(&changed).is_none());
        }
    }
    for (start, length) in [(165, 8), (173, 4)] {
        let mut changed = bytes.clone();
        changed[start..start + length].fill(0);
        assert!(parse(&changed).is_none());
    }
    let mut valid = fixture();
    valid.component = 1;
    valid.role = 2;
    valid.operation = 2;
    valid.head_hash = [0; 32]; // Digests have no reserved sentinel.
    valid.evidence_hash = [255; 32];
    valid.head_volume = u64::MAX - 1;
    valid.revision = u64::MAX;
    valid.status = u32::MAX;
    assert_eq!(parse(&valid.encode().unwrap()), Some(valid.clone()));
    valid.lifetime = [0; 32];
    assert!(valid.encode().is_none());
    valid = fixture();
    valid.status = 0;
    assert!(valid.encode().is_none());
}
