"""Validates fake-CLI argv against the real `treer` argument contract (apps/cli-contract.json).

The snapshot is generated by the cli_contract_snapshot_matches_the_real_parser test from the real clap definitions, so a
fake CLI that accepts a subcommand or flag the real parser rejects fails the Apps' tests instead of production.
"""

from __future__ import annotations

import json
from pathlib import Path

CONTRACT = json.loads((Path(__file__).with_name("cli-contract.json")).read_text(encoding="utf-8"))
GLOBAL_FLAGS = {"--workspace": "value", "--url": "value"}


def violation(arguments: list[str]) -> str | None:
    """None when the real CLI would parse `arguments`, otherwise why it would not."""
    arguments = list(arguments)
    while arguments and arguments[0] in GLOBAL_FLAGS:
        arguments = arguments[2:]
    best = ""
    for name in CONTRACT:
        words = name.split()
        if arguments[: len(words)] == words and len(name) > len(best):
            best = name
    if not best:
        return f"unknown command: treer {' '.join(arguments[:3])}"
    spec = CONTRACT[best]
    rest = arguments[len(best.split()) :]
    positionals = 0
    index = 0
    while index < len(rest):
        token = rest[index]
        if token == "--":
            positionals += len(rest) - index - 1
            break
        if token.startswith("--") and len(token) > 2:
            name, equals, _ = token.partition("=")
            takes_value = spec["flags"].get(name)
            if takes_value is None:
                return f"treer {best}: unknown option {name}"
            if takes_value != "none" and not equals:
                index += 1
                if index >= len(rest):
                    return f"treer {best}: {name} needs a value"
                if takes_value == "value" and rest[index].startswith("-") and rest[index] != "-":
                    # clap reads this as another option; text like "-1" or "--help" must be passed as --flag=VALUE
                    return f"treer {best}: a value is required for {name} (use {name}=VALUE for values starting with '-')"
        else:
            positionals += 1
        index += 1
    if positionals > spec["positionals"] and not spec["variadic"]:
        return f"treer {best}: unexpected argument"
    return None
