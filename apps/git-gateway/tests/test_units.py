NEW = "2" * 40
ZERO = "0" * 40


@functools.lru_cache(maxsize=1)
def test_key():
    """A throwaway 2048-bit PKCS#1 test key generated by openssl."""
    pem = subprocess.run(["openssl", "genrsa", "2048"], capture_output=True, text=True, check=True).stdout
    if "BEGIN PRIVATE KEY" in pem:  # OpenSSL 3 emits PKCS#8; GitHub hands out PKCS#1
        pem = subprocess.run(["openssl", "rsa", "-traditional"], input=pem, capture_output=True, text=True, check=True).stdout
    return pem, load_rsa_private_key(pem)


def b64(value: str) -> bytes:
    return base64.urlsafe_b64decode(value + "=" * (-len(value) % 4))


class Rs256Tests(unittest.TestCase):
    def test_signature_matches_openssl(self) -> None:
        pem, key = test_key()
        message = b"treer gateway signing input"
        with tempfile.TemporaryDirectory() as directory:
            key_path = Path(directory) / "key.pem"
            key_path.write_text(pem)
            expected = subprocess.run(["openssl", "dgst", "-sha256", "-sign", str(key_path)], input=message,
                                      capture_output=True, check=True).stdout
            self.assertEqual(rsa_sha256_sign(key, message), expected)  # PKCS#1 v1.5 is deterministic

    def test_pkcs8_key_and_jwt(self) -> None:
        pem, key = test_key()
        pkcs8 = subprocess.run(["openssl", "pkcs8", "-topk8", "-nocrypt"], input=pem, capture_output=True,
                               text=True, check=True).stdout
        self.assertIn("BEGIN PRIVATE KEY", pkcs8)
        self.assertEqual(load_rsa_private_key(pkcs8), key)
        token = github_app_jwt(1234, key, now=1_700_000_000)
        header, claims, signature = token.split(".")
        self.assertEqual(json.loads(b64(header)), {"alg": "RS256", "typ": "JWT"})
        self.assertEqual(json.loads(b64(claims)), {"iat": 1_699_999_940, "exp": 1_700_000_540, "iss": "1234"})
        with tempfile.TemporaryDirectory() as directory:
            public = Path(directory) / "pub.pem"
            subprocess.run(["openssl", "rsa", "-pubout", "-out", str(public)], input=pem, text=True,
                           capture_output=True, check=True)
            signature_path = Path(directory) / "sig"
            signature_path.write_bytes(b64(signature))
            verified = subprocess.run(["openssl", "dgst", "-sha256", "-verify", str(public), "-signature",
                                       str(signature_path)], input=f"{header}.{claims}".encode(), capture_output=True)
            self.assertEqual(verified.returncode, 0, verified.stderr)

    def test_rejects_bad_keys(self) -> None:
        for pem in ("nope", "-----BEGIN EC PRIVATE KEY-----\nAAAA\n-----END EC PRIVATE KEY-----"):
            with self.assertRaises(ValueError):
                load_rsa_private_key(pem)


class RuleTests(unittest.TestCase):
    agent = Caller("agent", "ag_worker", "Worker")
    leader = Caller("agent", "ag_leader", "Leader")
    human = Caller("human", "u_owner", "Owner")

    def config(self, **change):
        return validate_config({"trusted_agents": ["ag_leader"], **change})

    def test_patterns(self) -> None:
        self.assertTrue(match("refs/heads/agent/**", "refs/heads/agent/a/b"))
        self.assertFalse(match("refs/heads/agent/**", "refs/heads/agent/"))
        self.assertTrue(match("refs/heads/agent/*", "refs/heads/agent/a"))
        self.assertFalse(match("refs/heads/agent/*", "refs/heads/agent/a/b"))
        self.assertFalse(match("refs/heads/agent/*", "refs/heads/agentx"))

    def test_push_decisions(self) -> None:
        config = self.config()
        updates, _ = parse_receive_pack_commands(
            pkt(f"{OLD} {NEW} refs/heads/agent/x\0report-status side-band-64k\n".encode())
            + pkt(f"{OLD} {NEW} refs/heads/main\n".encode())
            + pkt(f"{OLD} {ZERO} refs/heads/main\n".encode())
            + b"0000PACK..."
        )
        self.assertEqual(push_decisions(config, self.agent, updates)[:2], [None, "gateway: Agents may push only refs/heads/agent/**"])
        self.assertEqual(push_decisions(config, self.leader, updates)[:2], [None, None])
        self.assertIn("protected", push_decisions(config, self.human, updates)[2])

    def test_command_parsing_and_gzip(self) -> None:
        body = (pkt(b"shallow " + b"3" * 40 + b"\n") + pkt(f"{ZERO} {NEW} refs/heads/agent/y\0report-status\n".encode())
                + b"0000" + b"PACK" + bytes(5000))
        updates, capabilities = parse_receive_pack_commands(body)
        self.assertEqual((updates[0].ref, updates[0].create, capabilities), ("refs/heads/agent/y", True, {"report-status"}))
        head = PushHead(gzip_encoded=True)
        compressed = gzip.compress(body)
        result = None
        for start in range(0, len(compressed), 7):
            result = head.feed(compressed[start : start + 7])
            if result:
                break
        self.assertEqual(result[0][0].ref, "refs/heads/agent/y")
        for bad in (pkt(b"garbage\n") + b"0000", pkt(f"{OLD} {NEW} main\n".encode()) + b"0000", b"zzzz"):
            with self.assertRaises(RuleError):
                parse_receive_pack_commands(bad)

    def test_rejection_round_trips_through_report_parser(self) -> None:
        updates, capabilities = parse_receive_pack_commands(
            pkt(f"{OLD} {NEW} refs/heads/main\0report-status side-band-64k\n".encode()) + b"0000")
        payload = receive_pack_rejection(updates, ["no"], capabilities)
        self.assertEqual(parse_report_status(payload, capabilities), {"refs/heads/main": "ng no"})
        self.assertEqual(parse_report_status(receive_pack_rejection(updates, ["no"], {"report-status"}), {"report-status"}),
                         {"refs/heads/main": "ng no"})

    def test_api_rules(self) -> None:
        config = self.config()
        self.assertEqual(api_decision(config, self.agent, "GET", "/repos/EvoEvolver/treer/actions/runs")[0], None)
        self.assertEqual(api_decision(config, self.agent, "GET", "/repos/evoevolver/TREER/pulls")[0], None)
        self.assertEqual(api_decision(config, self.agent, "POST", "/repos/EvoEvolver/treer/pulls")[0], None)
        self.assertEqual(api_decision(config, self.agent, "PUT", "/repos/EvoEvolver/treer/pulls/3/merge")[0], "agent_write_not_allowed")
        self.assertEqual(api_decision(config, self.leader, "PUT", "/repos/EvoEvolver/treer/pulls/3/merge")[0], None)
        self.assertEqual(api_decision(config, self.agent, "GET", "/rate_limit")[0], None)
        self.assertEqual(api_decision(config, self.agent, "GET", "/search/issues")[0], None)
        self.assertEqual(api_decision(config, self.human, "POST", "/graphql")[0], "path_not_allowed")
        self.assertEqual(api_decision(config, self.agent, "GET", "/repos/EvoEvolver/treer/%2e%2e")[0], "invalid_path")
        self.assertEqual(api_decision(config, self.agent, "TRACE", "/rate_limit")[0], "method_not_allowed")

    def test_config_validation(self) -> None:
        self.assertEqual(validate_config({})["repos"], DEFAULT_CONFIG["repos"])
        for bad in ({"repos": "x"}, {"repos": ["no-slash"]}, {"agent_push_refs": ["heads/x"]},
                    {"credential_mode": "pat"}, {"max_push_bytes": True}, {"agent_api_writes": ["GET /x"]},
                    {"trusted_agents": ["a b"]}, {"extra": 1}):
            with self.assertRaises(RuleError, msg=bad):
                validate_config(bad)


class GhTests(unittest.TestCase):
    def test_timer_refresh_and_invalidate(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            gh, token_file = fixture.fake_gh(Path(directory), "gho_first")
            now = [1000.0]
            credential = GhCredential(str(gh), refresh_seconds=600, clock=lambda: now[0])
            self.assertEqual(credential.token(), "gho_first")
            token_file.write_text("gho_second")
            now[0] += 599
            self.assertEqual(credential.token(), "gho_first")  # cached
            now[0] += 2
            self.assertEqual(credential.token(), "gho_second")  # timer re-read
            token_file.write_text("gho_third")
            credential.invalidate()
            self.assertEqual(credential.token(), "gho_third")  # re-read after GitHub 401
            self.assertEqual(credential.reads, 3)
            self.assertEqual(credential.describe()["token_type"], "gho")
            token_file.write_text("")
            credential.invalidate()
            with self.assertRaises(Exception):
                credential.token()
            self.assertIn("gh auth login", credential.describe()["error"])


