        self.assertEqual(before,(self.root/'relay.json').read_bytes())
        os.environ['TREER_AGENT_ID']='ag_other'
        with self.assertRaisesRegex(ValueError,'existing_binding_mismatch'):bootstrap.prepare(str(path))
        self.assertEqual(before,(self.root/'relay.json').read_bytes())

