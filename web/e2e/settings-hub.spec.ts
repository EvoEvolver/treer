test('the Worker serves settings deep links as the Console document', async ({ request }) => {
  for (const path of ['/settings/profile', '/orgs/org-acme/settings/members', '/orgs/org-acme/workspaces/ws-main/settings/access']) {
    const response = await request.get(`${workerOrigin}${path}`)
    expect(response.status(), path).toBe(200)
    expect(response.headers()['content-type'], path).toContain('text/html')
    expect(await response.text(), path).toContain('<div id="root">')
  }
})

