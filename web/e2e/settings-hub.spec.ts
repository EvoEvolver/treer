// Settings are pages with real URLs: deep links, reload and Back all work.
test('settings deep links survive reload and Back, and the desktop root opens the first page', async ({ page }) => {
  await mockHub(page)
  await page.goto('/orgs/org-acme/settings/members')
  await expect(page.getByRole('heading', { name: 'Members', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Members', exact: true })).toBeVisible()
  const nav = page.getByRole('navigation', { name: 'Settings' })
  await expect(nav.getByRole('link', { name: 'Members' })).toHaveAttribute('aria-current', 'page')
  await nav.getByRole('group', { name: 'Acme Research' }).getByRole('link', { name: 'Groups' }).click()
  await expect(page).toHaveURL(/\/orgs\/org-acme\/settings\/groups$/)
  await page.goBack()
  await expect(page).toHaveURL(/\/orgs\/org-acme\/settings\/members$/)
  await expect(page.getByRole('heading', { name: 'Members', exact: true })).toBeVisible()
  await page.goForward()
  await expect(page.getByRole('heading', { name: 'Groups', exact: true })).toBeVisible()
  // Leaving settings returns to the workspace, which stayed loaded.
  await nav.getByRole('button', { name: 'Back to Main' }).click()
  await expect(page).toHaveURL(/\/orgs\/org-acme\/workspaces\/ws-main$/)
  await expect(page.getByRole('heading', { name: 'Workspace overview' })).toBeVisible()
  await page.goto('/settings')
  await expect(page).toHaveURL(/\/settings\/profile$/)
  await page.goto('/orgs/org-acme/workspaces/ws-main/settings/nonsense')
  await expect(page.getByRole('alert')).toContainText('This settings page does not exist.')
  await page.goto('/orgs/org-unknown/settings/general')
  await expect(page.getByRole('alert')).toContainText('This organization does not exist or you are not a member.')
  await page.goto('/orgs/org-acme/workspaces/ws-gone/settings/general')
  await expect(page.getByRole('alert')).toContainText('This workspace does not exist or you do not have access to it.')
})

